function doc(
  id: string,
  title: string,
  category: string,
  overview: string,
  points: string[],
): KnowledgeDoc {
  return {
    id,
    title,
    category,
    body: [
      "## 概览",
      "",
      overview,
      "",
      "## 关键约束",
      "",
      ...points.map((x) => `- ${x}`),
      "",
      "## 操作与协作",
      "",
      "变更前确认相关上下游，处理过程中记录可复现的查询条件与证据；涉及异常时同步负责人和下一次更新时间。",
      "",
      "```yaml",
      `# ${title}`,
      "owner: 研发工作区",
      "status: 已维护",
      "last_reviewed: 2026-09-02",
      "```",
      "",
      "> 本篇为阶段一示例正文，用于验证 Markdown 阅读体验。",
    ].join("\n"),
  };
}

